def calculate_metrics(predictions, references):
    intersection = torch.logical_and(predictions, references).sum().item()
    union = torch.logical_or(predictions, references).sum().item()
    mean_iou = intersection / union
    accuracy = (predictions == references).float().mean().item()
    return mean_iou, accuracy

def objective(trial):
    learning_rate = trial.suggest_loguniform("learning_rate", 1e-4, 1e-1)
    momentum = trial.suggest_uniform("momentum", 0.9, 0.999)
    weight_decay = trial.suggest_loguniform("weight_decay", 1e-5, 1e-3)

    optimizer = torch.optim.SGD(model.parameters(), lr=learning_rate, momentum=momentum, weight_decay=weight_decay)
    scaler = torch.cuda.amp.GradScaler()  # For mixed precision training

    num_epochs = trial.suggest_int("num_epochs", 5, 50)
    patience = 3
    best_val_loss = float('inf')
    counter = 0

    for epoch in range(num_epochs):
        model.train()
        for idx, batch in enumerate(tqdm(train_dataloader, desc=f"Epoch {epoch+1}")):
            pixel_values = batch["pixel_values"].to(device, non_blocking=True)
            labels = batch["labels"].to(device, non_blocking=True)
            original_images = batch["original_images"]
            original_segmentation_maps = batch["original_segmentation_maps"]

            optimizer.zero_grad()
            with torch.cuda.amp.autocast():  # Mixed precision context
                outputs = model(pixel_values, labels=labels)
                loss = outputs.loss

            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()

            if idx % 100 == 0:  # Reduce frequency of printing
                with torch.no_grad():
                    predicted = outputs.logits.argmax(dim=1)
                    metric.add_batch(predictions=predicted.detach().cpu().numpy(), references=labels.detach().cpu().numpy())
                    metrics = metric.compute(num_labels=len(id2label), ignore_index=0, reduce_labels=False)

                print(f"Epoch: {epoch}, Batch: {idx}, Loss: {loss.item()}, Mean IoU: {metrics['mean_iou']}, Mean Accuracy: {metrics['mean_accuracy']}")

        model.eval()
        val_loss = 0.0
        with torch.no_grad():
            for batch in val_dataloader:
                pixel_values = batch['pixel_values'].to(device, non_blocking=True)
                labels = batch['labels'].to(device, non_blocking=True)
                original_images = batch['original_images']
                original_segmentation_maps = batch['original_segmentation_maps']

                outputs = model(pixel_values, labels=labels)
                loss = outputs.loss

                val_loss += loss.item()

        val_loss /= len(val_dataloader)

        print(f"Epoch {epoch+1}, Validation Loss: {val_loss}")

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            counter = 0
        else:
            counter += 1
            if counter >= patience:
                print(f"Early stopping at epoch {epoch+1} with best validation loss: {best_val_loss}")
                break

    return best_val_loss

